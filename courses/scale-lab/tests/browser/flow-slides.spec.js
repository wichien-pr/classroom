import {test,expect} from '@playwright/test';

test('LAB01 slides skip without running the simulation and retain its state',async({page})=>{
 await page.goto('/');
 const next=page.getByRole('button',{name:'ถัดไป · Next',exact:true});
 const back=page.getByRole('button',{name:'ย้อนกลับ · Back',exact:true});
 await expect(page.locator('#flow-slide-title')).toContainText('1 / 4');
 await expect(back).toBeDisabled();
 const topic=page.locator('#flow-topic');
 await expect(topic.locator('#step')).toBeVisible();
 await expect(topic.locator('#outcome')).toBeVisible();
 await expect(topic.locator('.flow-topic-map:visible')).toContainText('DNS');
 await expect(topic.locator('#state-view > div').nth(3)).toBeHidden();
 await next.click();
 await expect(topic).toHaveAttribute('data-topic','1');
 await expect(topic.locator('.flow-topic-map:visible')).toContainText('Web / Application');
 await expect(page.locator('#flow-client')).toBeHidden();
 await expect(topic.locator('#state-view > div').nth(3)).toBeVisible();
 await back.click();
 for(let i=0;i<3;i++)await next.click();
 await expect(next).toBeDisabled();
 await expect(page.locator('#flow-slide-title')).toContainText('4 / 4');
 await expect(page.locator('#architecture svg')).toHaveAttribute('data-stage','ready');
 await expect(page.locator('#event-log')).toContainText('ยังไม่มีเหตุการณ์');
 await expect(page.locator('#progress')).toContainText('0 /');
 await page.locator('#flow-client').selectOption('mobile');
 await page.locator('#step').click();
 await back.click();
 await expect(page.locator('#flow-client')).toHaveValue('mobile');
 await expect(page.locator('.flow-topic-map:visible')).toContainText('Mobile app');
 await expect(page.locator('#architecture svg')).toHaveAttribute('data-stage','dns-query');
 await expect(page.locator('.flow-steps li:visible')).toHaveCount(1);
 await expect(page.locator('#flow-slide-title')).toBeFocused();
 await page.keyboard.press('Tab');
 await expect(page.locator(':focus')).not.toHaveCount(0);
 await next.click();
 for(let i=0;i<5;i++)await page.locator('#step').click();
 await expect(page.locator('#flow-payload')).toContainText('"id": 12');
 const log=await page.locator('#event-log').textContent();await page.locator('#step').click();
 await expect(page.locator('#event-log')).toHaveText(log);
 await page.locator('#reset').click();
 await expect(page.locator('#flow-slide-title')).toContainText('1 / 4');
 await expect(page.locator('#architecture svg')).toHaveAttribute('data-stage','ready');
 await page.locator('[data-lesson-kind="workload"]').click();
 await expect(page.locator('#flow-slide-title')).toHaveCount(0);
 await page.locator('[data-lesson-kind="flow"]').click();
 await expect(page.locator('#flow-slide-title')).toContainText('1 / 4');
});
