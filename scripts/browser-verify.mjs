import {mkdir, writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {completeRegistration} from './complete-registration.mjs';
process.env.PLAYWRIGHT_BROWSERS_PATH = new URL('../courses/scale-lab/.browsers', import.meta.url).pathname;
const {chromium} = await import('../courses/scale-lab/node_modules/playwright/index.mjs');
const browser = await chromium.launch({channel:'chromium'});
const page = await browser.newPage({viewport:{width:1440,height:1000}});
const errors = [], assets=[];
page.on('pageerror', e=>errors.push(String(e)));
page.on('response', r=> {if(r.url().includes('/courses/') && /\.(js|css|woff2?)(\?|$)/.test(r.url()))assets.push({url:r.url(),status:r.status()});});
const base=process.env.CLASSROOM_QA_URL || 'http://127.0.0.1:8093';
try {
  await page.goto(base+'/courses/scale-lab/');
  assert.equal(page.url(),base+'/login');
  const guest = await page.request.get(base+'/courses/scale-lab/assets/guest-probe.js',{maxRedirects:0});
  assert.equal(guest.status(),303);
  await page.goto(base+'/register');
  const email=`modular-${Date.now()}@example.test`;
  await page.locator('[name=name]').fill('Modular QA');
  await page.locator('[name=email]').fill(email);
  await page.locator('[name=password]').fill('modular browser password');
  await page.locator('button').click();
  await completeRegistration(page,email);
  await page.locator('[name=email]').fill(email);
  await page.locator('[name=password]').fill('modular browser password');
  await page.locator('button').click();
  await page.waitForURL(base+'/');
  await page.locator('a[href="/courses/scale-lab/"]').click();
  await page.locator('#step').waitFor();
  await page.locator('#step').click();
  assert.ok((await page.locator('#event-log').innerText()).length>0);
  await mkdir(new URL('../evidence/',import.meta.url),{recursive:true});
  await page.screenshot({path:new URL('../evidence/authenticated-scale-lab.png',import.meta.url).pathname,fullPage:true});
  await page.getByRole('link',{name:'ออกจากคลาส · กลับหน้าแรก'}).click();
  await page.waitForURL(base+'/');
  await page.goto(base+'/courses/scale-lab/labs/replication');
  await page.locator('#step').waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:new URL('../evidence/authenticated-scale-lab-mobile.png',import.meta.url).pathname,fullPage:true});
  await page.goto(base+'/');
  await page.getByRole('button',{name:'ออกจากระบบ'}).click();
  await page.waitForURL('**/login');
  await page.goto(base+'/courses/scale-lab/');
  assert.equal(page.url(),base+'/login');
  assert.ok(assets.length>=2);
  assert.ok(assets.every(a=>a.status===200));
  assert.deepEqual(errors,[]);
  const result={base,passed:true,guestRedirect:true,registerLogin:true,interactiveLab:true,returnNavigation:true,deepRoute:true,mobileNoOverflow:true,logoutProtection:true,assets,errors};
  await writeFile(new URL('../evidence/platform-browser.json',import.meta.url),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
} finally {await browser.close();}
